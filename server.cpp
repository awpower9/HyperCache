static const uint8_t *find_crlf(const uint8_t *data, size_t size) {
    for (size_t i = 0; i + 1 < size; ++i) {
        if (data[i] == '\r' && data[i+1] == '\n') return data + i;
    }
    return NULL;
}

static bool parse_req_resp(const uint8_t *data, size_t size, size_t &consumed, std::vector<std::string> &out) {
    if (size == 0) return false;
    const uint8_t *p = data;
    const uint8_t *end = data + size;
    
    if (p[0] == '*') {
        const uint8_t *crlf = find_crlf(p, end - p);
        if (!crlf) return false;
        
        int num_args = atoi((const char *)p + 1);
        if (num_args <= 0) { consumed = crlf + 2 - data; return true; }
        
        p = crlf + 2;
        for (int i = 0; i < num_args; ++i) {
            if (p >= end) return false;
            if (p[0] != '$') return false;
            crlf = find_crlf(p, end - p);
            if (!crlf) return false;
            
            int str_sz = atoi((const char *)p + 1);
            p = crlf + 2;
            if (p + str_sz + 2 > end) return false;
            
            out.push_back(std::string((const char *)p, str_sz));
            p += str_sz + 2;
        }
        consumed = p - data;
        return true;
    } else {
        const uint8_t *crlf = find_crlf(p, end - p);
        if (!crlf) return false;
        std::string cmd_line((const char *)p, crlf - p);
        size_t start = 0;
        while (start < cmd_line.size()) {
            size_t space = cmd_line.find(' ', start);
            if (space == std::string::npos) {
                out.push_back(cmd_line.substr(start));
                break;
            }
            if (space > start) {
                out.push_back(cmd_line.substr(start, space - start));
            }
            start = space + 1;
        }
        consumed = crlf + 2 - data;
        return true;
    }
}

