struct Conn {
    socket_t fd = -1;
    // application's intention, for the event loop
    bool want_read = false;
    bool want_write = false;
    bool want_close = false;
    // buffered input and output
    Buffer incoming;    // data to be parsed by the application
    Buffer outgoing;    // responses generated by the application
    
    // transaction state
    bool in_transaction = false;
    std::vector<std::vector<std::string>> tx_queue;

    // pub/sub state
    bool is_subscribed = false;
    std::unordered_set<std::string> subscribed_channels;
};

// application callback when the listening socket is ready
static Conn *handle_accept(socket_t fd) {
    // accept
    struct sockaddr_in client_addr = {};
    socklen_t addrlen = sizeof(client_addr);
    socket_t connfd = accept(fd, (struct sockaddr *)&client_addr, &addrlen);
    if (connfd < 0) {
        msg_errno("accept() error");
        return NULL;
    }
    uint32_t ip = client_addr.sin_addr.s_addr;
    fprintf(stderr, "new client from %u.%u.%u.%u:%u\n",
        ip & 255, (ip >> 8) & 255, (ip >> 16) & 255, ip >> 24,
        ntohs(client_addr.sin_port)
    );

    // set the new connection fd to nonblocking mode
    fd_set_nb(connfd);

    // enable TCP_NODELAY
    int val = 1;
    setsockopt(connfd, IPPROTO_TCP, TCP_NODELAY, (const char *)&val, sizeof(val));

    // create a `struct Conn`
    Conn *conn = new Conn();
    conn->fd = connfd;
    conn->want_read = true;
    g_total_connections.fetch_add(1, std::memory_order_relaxed);
    g_current_connections.fetch_add(1, std::memory_order_relaxed);
    return conn;
}

